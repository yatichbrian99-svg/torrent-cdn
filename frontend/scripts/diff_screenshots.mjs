#!/usr/bin/env node
/**
 * Pixel diff between two screenshot sets.
 *
 * Used for the freeze proof: /embed and /share (and the SDK) must look exactly
 * as they did before the redesign. Pairing is by filename without a tag prefix,
 * so `before-embed_demo-dark-1280.png` is compared with
 * `after-embed_demo-dark-1280.png`.
 *
 * Images are decoded in Chromium (canvas) rather than through an image
 * dependency, so the repo gains nothing new to install or audit.
 *
 *   node scripts/diff_screenshots.mjs --before ../docs/.../baseline --after ../docs/.../screenshots \
 *        --prefix embed --max-diff 0
 *
 * Exit code 1 when any pair differs by more than `--max-diff` pixels.
 */
import { chromium } from 'playwright'
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 ? args[i + 1] : fallback
}
const BEFORE = arg('before')
const AFTER = arg('after')
const PREFIX = arg('prefix', 'embed')
const MAX_DIFF = Number(arg('max-diff', '0'))
const OUT = arg('out', path.join(process.cwd(), '..', 'docs', 'frontend', 'evidence', 'frozen-surface-diff.md'))

if (!BEFORE || !AFTER) {
  console.error('usage: --before <dir> --after <dir> [--prefix embed] [--max-diff 0]')
  process.exit(2)
}

const beforeFiles = readdirSync(BEFORE).filter((f) => f.startsWith('before-') && f.endsWith('.png'))
const afterFiles = readdirSync(AFTER).filter((f) => f.startsWith('after-') && f.endsWith('.png'))

const pairs = []
for (const b of beforeFiles) {
  const name = b.slice('before-'.length)
  if (!name.startsWith(PREFIX)) continue
  const a = `after-${name}`
  if (!afterFiles.includes(a)) continue
  pairs.push({ name, before: path.join(BEFORE, b), after: path.join(AFTER, a) })
}

if (pairs.length === 0) {
  console.error(`no ${PREFIX}* pairs found between ${BEFORE} and ${AFTER}`)
  process.exit(2)
}

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage()
const rows = []
let failures = 0

try {
  for (const pair of pairs) {
    const beforeData = `data:image/png;base64,${readFileSync(pair.before).toString('base64')}`
    const afterData = `data:image/png;base64,${readFileSync(pair.after).toString('base64')}`
    const result = await page.evaluate(
      async ({ a, b }) => {
        const load = (src) =>
          new Promise((resolve, reject) => {
            const img = new Image()
            img.onload = () => resolve(img)
            img.onerror = reject
            img.src = src
          })
        const [ia, ib] = [await load(a), await load(b)]
        if (ia.width !== ib.width || ia.height !== ib.height) {
          return { widthDiff: [ia.width, ia.height, ib.width, ib.height], differing: null }
        }
        const draw = (img) => {
          const canvas = document.createElement('canvas')
          canvas.width = img.width
          canvas.height = img.height
          const ctx = canvas.getContext('2d')
          ctx.drawImage(img, 0, 0)
          return ctx.getImageData(0, 0, img.width, img.height).data
        }
        const da = draw(ia)
        const db = draw(ib)
        let differing = 0
        let maxChannelDelta = 0
        for (let i = 0; i < da.length; i += 4) {
          const dr = Math.abs(da[i] - db[i])
          const dg = Math.abs(da[i + 1] - db[i + 1])
          const dbl = Math.abs(da[i + 2] - db[i + 2])
          const max = Math.max(dr, dg, dbl)
          if (max > 0) differing++
          if (max > maxChannelDelta) maxChannelDelta = max
        }
        return { differing, maxChannelDelta, pixels: da.length / 4, width: ia.width, height: ia.height }
      },
      { a: beforeData, b: afterData },
    )

    const ok = result.differing !== null && result.differing <= MAX_DIFF
    if (!ok) failures++
    rows.push({ ...pair, ...result, ok })
  }
} finally {
  await browser.close()
}

const lines = [
  '# Frozen-surface pixel diff',
  '',
  '`/embed` and `/share` are excluded from the restyle: the redesign pins their',
  'pre-redesign palette (`[data-frozen-surface]`), keeps a verbatim copy of the',
  'old navbar (`components/LegacyChrome.tsx`) and does not touch',
  '`public/sdk.js`. These pairs are the proof.',
  '',
  `Generated by \`frontend/scripts/diff_screenshots.mjs\` (pixel comparison in`,
  `Chromium). Allowed difference: ${MAX_DIFF} px.`,
  '',
  '| Shot | Size | Differing pixels | Max channel Δ | Result |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| ${r.name} | ${r.width ? `${r.width}×${r.height}` : `size mismatch ${JSON.stringify(r.widthDiff)}`} | ${
        r.differing ?? 'n/a'
      } | ${r.maxChannelDelta ?? 'n/a'} | ${r.ok ? 'identical' : '**DIFFERS**'} |`,
  ),
  '',
  failures === 0 ? 'All frozen-surface shots are pixel-identical.' : `${failures} shot(s) differ.`,
  '',
]
mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, lines.join('\n'))
console.log(lines.slice(-3).join('\n'))
console.log(`report: ${OUT}`)
process.exit(failures ? 1 : 0)
